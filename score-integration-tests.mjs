import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {scoreRun} from './dist/scoring.js';
import {liveScoreMarkup as scoreMarkup} from './dist/live-score-view.js';
import {DOCK, SUPPORT_PICKUP_RADIUS} from './dist/logic.js';

let harness = await fs.readFile('integration-tests.mjs', 'utf8');
harness = harness.slice(0, harness.indexOf("el('help').click()"));
harness = harness.replace("from './dist/logic.js'", `from ${JSON.stringify(new URL('./dist/logic.js', import.meta.url).href)}`);
harness += '\nglobalThis.scoreHarness={advance,el};';
await import('data:text/javascript;base64,' + Buffer.from(harness).toString('base64'));
const {advance, el} = scoreHarness;
const supplyPoints = run => scoreRun(run).rows.find(row => row.id === 'supplies').points;

el('start').click();
let r = getGameTestState().run;
r.time = 130;
r.health = 1;
r.hits = 1;
r.distance = 200;
r.supportEarned = 1;
r.supportDispatched = 1;
r.supportPending = {id: 1, kind: 'health', at: r.time, deliverAt: r.time + .1, x: r.x + 22, z: r.z};
const beforePickup = scoreRun(r);
assert.equal(supplyPoints(r), 0, 'dispatch earns no points');
advance(.2);
assert(r.supportDrop);
assert.equal(r.supportDelivered, 1);
assert.equal(r.supportCollected, 0);
assert.equal(supplyPoints(r), 0, 'landing earns no points');
assert.equal(scoreRun(r).total, beforePickup.total);
r.x = r.supportDrop.x;
r.z = r.supportDrop.z;
r.speed = 0;
advance(.1);
assert.equal(r.supportCollected, 1);
assert.equal(r.supportDrop, null);
assert.equal(supplyPoints(r), 250);
assert.equal(scoreRun(r).total - beforePickup.total, 550, 'health pickup adds 250 directly and restores 300 hull points');
assert.equal(scoreRun(r).rows.find(row => row.id === 'hits').points, -400);
const afterPickup = scoreRun(r).total;
advance(.3);
assert.equal(scoreRun(r).total, afterPickup, 'the same pickup cannot score repeatedly');
r.supportEarned = 2;
r.supportDispatched = 2;
r.supportDelivered = 2;
r.supportDrop = {id: 2, kind: 'boost', spawnedAt: r.time, expiresAt: r.time + .1, x: r.x + 22, z: r.z, radius: SUPPORT_PICKUP_RADIUS};
advance(.2);
assert.equal(r.supportIgnored, 1);
assert.equal(supplyPoints(r), 250, 'an ignored second crate adds no points');
assert.equal(scoreRun(r).total, afterPickup);

r.distance = 1799;
r.x = DOCK.x;
r.z = -1799.9;
r.speed = 2;
advance(.1);
assert.equal(getGameTestState().state, 'docking');
advance(3.6);
assert.equal(getGameTestState().state, 'won');
assert.equal(el('score-report').innerHTML, scoreMarkup(r));
assert(el('score-report').innerHTML.includes('YOUR VOYAGE'));
assert(!el('score-report').innerHTML.includes('SAMPLE VOYAGE'));
assert(el('score-report').innerHTML.includes('PRACTICE'));
assert(el('score-report').innerHTML.includes('1 crate × 250 points'));
assert(el('result').classList.contains('hidden'), 'score waits for the opening dance beat');
const won = scoreRun(r);
assert.equal(won.rows.reduce((n, row) => n + row.points, 0), won.total);
assert.equal(won.total - scoreRun({...r, supportCollected: 0}).total, 250);
const frozen = el('score-report').innerHTML;
advance(12);
assert.equal(el('score-report').innerHTML, frozen);
assert(!el('result').classList.contains('hidden'));
el('result').scrollTop = 900;
el('again').click();
assert.equal(getGameTestState().state, 'playing');
assert(el('result').classList.contains('hidden'));

r = getGameTestState().run;
assert.equal(r.supportCollected, 0, 'replay starts without the previous pickup score');
assert.equal(supplyPoints(r), 0);
r.time = 112.8;
r.distance = 1480.6;
r.health = 0;
r.hits = 2;
r.state = 'lost';
advance(.1);
assert.equal(getGameTestState().state, 'lost');
assert.equal(scoreRun(r).total, 680);
assert.equal(el('result').scrollTop, 0, 'new debrief resets previous scroll');
assert.equal(el('score-report').innerHTML, scoreMarkup(r));
assert(!el('result').classList.contains('hidden'));
assert(el('score-report').innerHTML.includes('−800'));
assert(el('score-report').innerHTML.includes('0 crates × 250 points'));
assert(el('score-report').innerHTML.includes('No account required.'));

el('again').click();
r = getGameTestState().run;
r.distance = 1480.6;
r.supportEarned = 1;
r.supportDispatched = 1;
r.supportDelivered = 1;
r.supportDrop = {id: 1, kind: 'boost', spawnedAt: r.time, expiresAt: r.time + 45, x: r.x, z: r.z, radius: SUPPORT_PICKUP_RADIUS};
advance(.1);
assert.equal(r.supportCollected, 1);
r.health = 0;
r.hits = 2;
r.state = 'lost';
advance(.1);
assert.equal(getGameTestState().state, 'lost');
assert.equal(scoreRun(r).total, 930, 'lost voyage retains its collected supply points');
assert.equal(el('score-report').innerHTML, scoreMarkup(r));
assert(el('score-report').innerHTML.includes('1 crate × 250 points'));
assert(el('score-report').innerHTML.includes('−800'));

const files = ['dist/scoring.js', 'dist/score-view.js', 'dist/score-preview.js'];
for (const path of files) {
  const source = await fs.readFile(path, 'utf8');
  assert(!/localStorage|sessionStorage|fetch\s*\(|XMLHttpRequest|WebSocket/.test(source), `${path} cannot persist or submit scores`);
}
console.log('PASS: physical pickups score once, dispatch/delivery/ignore do not; won/lost scorecards retain supply points, damage costs, celebration timing and honest practice disclosure; replay resets scoring; no score network or persistence.');
